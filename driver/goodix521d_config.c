static uint16_t
rd16 (const uint8_t *p)
{
  return p[0] | (p[1] << 8);
}

static void
wr16 (uint8_t *p, uint16_t v)
{
  p[0] = v & 0xff;
  p[1] = v >> 8;
}

static uint16_t
config_checksum (const uint8_t *c)
{
  uint16_t s = 0xa5a5;

  for (int i = 0; i < 127; i++)
    s += rd16 (c + 2 * i);
  return -s;
}

/* Registers are (address, value) LE16 pairs in sections; the section table
 * at the start gives each section's offset and length. */
static int
set_register (uint8_t *c, int section, uint16_t reg, uint16_t value)
{
  int start = c[1 + 2 * section], len = c[2 + 2 * section];

  for (int p = start; p + 4 <= start + len; p += 4)
    if (rd16 (c + p) == reg)
      {
        wr16 (c + p + 2, value);
        return 0;
      }
  return -1;
}

int
goodix521d_build_config (const uint8_t otp[GOODIX521D_OTP_LEN],
                         uint8_t       config[GOODIX521D_CONFIG_LEN],
                         uint16_t      dacs[4])
{
  uint16_t tcode, fdt_tcode, delta;
  uint8_t x;

  if (memcmp (otp, "NLM1", 4) != 0)
    return -1;

  tcode = otp[0x1b] ? otp[0x1b] * 2 : 0;
  fdt_tcode = otp[0x20];
  x = otp[0x17] & 0x3e;
  delta = x ? ((x >> 1) + 1) / 3 : 0xd;

  memcpy (config, config_template, GOODIX521D_CONFIG_LEN);
  if (set_register (config, 4, 0x5c, tcode) < 0 ||
      set_register (config, 2, 0x5c, fdt_tcode) < 0 ||
      set_register (config, 2, 0x82, (delta << 8) | 0x80) < 0)
    return -1;
  wr16 (config + 0xfe, config_checksum (config));

  /* High DACs: the levels the Windows driver captures with. */
  dacs[0] = ((otp[0x17] & 0x01) << 8) | otp[0x1a];
  dacs[1] = ((otp[0x28] & 0x08) << 5) | otp[0x2c];
  dacs[2] = ((otp[0x28] & 0x10) << 4) | otp[0x2d];
  dacs[3] = ((otp[0x28] & 0x20) << 3) | otp[0x2e];
  return 0;
}
